"""Film intelligence (UNIT r3-film, feature module, docs/PLUGINS.md): richer «عن الفيلم» content — scores
(RT critics/audience/consensus, IMDb only with OMDB_KEY configured), «ليش يستاهل / ليش لا», «رأي الجمهور» and
a fun fact, plus two spoiler-gated disclosures («اشرح النهاية» and «أسئلة عن الفيلم») built only from a sourced
Wikipedia plot. Data: filmintel.py (intel/<fid>.json, generated by steps/intel.py) and omdb.py
(film["imdb_score"]). Fills the film.info slot (pages/_core/film.py's film_about: "after the synopsis and
facts") — no core page module touched, per docs/PLUGINS.md's whole-registration-is-the-module rule.

Everything here is a plain <details>/<summary> (no script): expanding a spoiler IS the consent — the "بدون
حرق" default is simply every <details> closed, so a first-time visitor sees only the closed, labelled
buttons. A film with no intel file (no basis yet, or the run hasn't reached it) renders nothing extra — never
an empty or broken section (honesty rule, feedback_emirati_dialect.md)."""
from site_kit import Plugin, dates, esc, num

CSS = ("intel",)

L = {
    "scores": ("التقييمات", "Ratings"),
    "consensus": ("رأي النقاد بالمجمل", "Critics' consensus"),
    "imdb": ("IMDb", "IMDb"),
    "why": ("ليش يستاهل؟", "Why (not)?"),
    "audience": ("رأي الجمهور", "What people are saying"),
    "fact": ("معلومة", "Fun fact"),
    "ending_btn": ("اشرح النهاية", "Explain the ending"),
    "qa_btn": ("أسئلة عن الفيلم", "Questions about this film"),
    "spoiler_warn": ("تحذير: يحرق الفيلم — اضغط بس إذا شفته", "Spoiler warning — tap only if you've seen it"),
    "no_answer": ("ما عندنا جواب أكيد للحين.", "We don't have a solid answer yet."),
}


def _score_row(film, lang):
    rt = film.get("rt") or {}
    rows = []
    if rt.get("critics") is not None:
        rows.append(("النقاد" if lang == "ar" else "Critics", num(str(rt["critics"]) + "%")))
    if rt.get("audience") is not None:
        rows.append(("الجمهور" if lang == "ar" else "Audience", num(str(rt["audience"]) + "%")))
    imdb_score = film.get("imdb_score")
    if isinstance(imdb_score, (int, float)):
        rows.append((L["imdb"][0 if lang == "ar" else 1], num(f"{imdb_score:.1f}")))
    out = ""
    if rows:
        out += ('<dl class="facts scores">'
                + "".join(f'<div><dt>{esc(a)}</dt><dd>{v}</dd></div>' for a, v in rows) + '</dl>')
    if rt.get("consensus"):
        out += f'<p class="consensus"><b>{esc(L["consensus"][0 if lang == "ar" else 1])}:</b> {esc(rt["consensus"])}</p>'
    if not out:
        return ""
    return f'<div class="i-scores"><h3 class="i-h">{esc(L["scores"][0 if lang == "ar" else 1])}</h3>{out}</div>'


def _reasons(intel, lang):
    reasons = intel.get("reasons") or []
    if not reasons:
        return ""
    items = "".join(f'<li class="{"pos" if r.get("pos") else "neg"}">{dates(esc(r.get("text", "")))}</li>' for r in reasons)
    return (f'<details class="i-d i-reasons"><summary>{esc(L["why"][0 if lang == "ar" else 1])}</summary>'
            f'<ul class="i-list">{items}</ul></details>')


def _audience(intel, lang):
    pts = intel.get("audience") or []
    if not pts:
        return ""
    items = "".join(f'<li>{dates(esc(p.get("text", "")))} <span class="src">— {esc(p.get("source", ""))}</span></li>' for p in pts)
    return (f'<details class="i-d i-audience"><summary>{esc(L["audience"][0 if lang == "ar" else 1])}</summary>'
            f'<ul class="i-list">{items}</ul></details>')


def _fact(intel, lang):
    ff = intel.get("fun_fact")
    if not ff or not ff.get("text"):
        return ""
    return (f'<p class="i-fact"><b>{esc(L["fact"][0 if lang == "ar" else 1])}:</b> {dates(esc(ff["text"]))} '
            f'<span class="src">— {esc(ff.get("source", ""))}</span></p>')


def _spoiler(intel, lang):
    """Both disclosures render whenever intel exists at all, so a visitor always sees the two buttons on a
    film we have written anything about; a film with no sourced plot answers with the fixed no-answer line
    instead of a fabricated one (spec: "if no source, say «ما عندنا جواب أكيد للحين»")."""
    has_plot = bool(intel.get("has_plot"))
    warn = esc(L["spoiler_warn"][0 if lang == "ar" else 1])
    ending = intel.get("ending") if has_plot else None
    ending_body = dates(esc(ending)) if ending else esc(L["no_answer"][0 if lang == "ar" else 1])
    end_d = (f'<details class="i-d i-spoiler"><summary>{esc(L["ending_btn"][0 if lang == "ar" else 1])}</summary>'
             f'<p class="i-warn">{warn}</p><p>{ending_body}</p></details>')
    qa = (intel.get("qa") or []) if has_plot else []
    if qa:
        qa_body = "".join(f'<div class="i-qa"><p class="q">{dates(esc(x.get("q", "")))}</p>'
                          f'<p class="a">{dates(esc(x.get("a", "")))}</p></div>' for x in qa)
    else:
        qa_body = f'<p>{esc(L["no_answer"][0 if lang == "ar" else 1])}</p>'
    qa_d = (f'<details class="i-d i-spoiler"><summary>{esc(L["qa_btn"][0 if lang == "ar" else 1])}</summary>'
            f'<p class="i-warn">{warn}</p>{qa_body}</details>')
    return end_d + qa_d


def _film_info(site, lang, fid):
    film = site.films.get(fid) or {}
    intel = film.get("intel")
    out = _score_row(film, lang)
    if intel:
        out += _reasons(intel, lang) + _audience(intel, lang) + _fact(intel, lang) + _spoiler(intel, lang)
    return f'<div class="i-wrap">{out}</div>' if out else ""


def register(site):
    return Plugin(slots={"film.info": _film_info})
