"""Bilingual fuzzy search (phase 3, batch A, task A5): a compact index at /data/search.json and the client
chunk src/js/search.js that reads it. No page of its own — this module only feeds data and a lazy chunk.

The index: every film (site.films — showing and archived, each still has a page), every cinema, and every
person with a real /people/<slug>/ page (pages/people.py's own `People` filter, imported rather than re-derived,
so search never lists someone whose page does not exist). A mall (malls.yaml) is not a row of its own: its names
are keys of every cinema it lists (W1-D2 fix round), so «دبي مول» lands on both of its cinemas once each; a mall
that malls.yaml does not tie to a cinema is never guessed at (venue.py's rule).

Per entry: its Arabic/English names, the site path (joined without a leading/trailing slash — the client
builds the language-correct href from `C.base`), a poster/photo where one exists, and `k`: normalised keys
generated BY RULE from the Arabic and English names (see `normalize()`), not hand-written per title. Folding
"Spider-Man", "Spider Man" and "spiderman" all removes spaces/punctuation and case, so they collapse to the
same key on both sides — the query is folded with the exact same rule client-side (src/js/search.js). That
single mechanism is what the brief calls "a few common variants" without anyone listing them by hand.

The index learns Arabic (W1-D2, MASTER-PLAN §2.7):
  - names are the site's own: a cinema is its cinemas.yaml «chain — mall» name in both languages (all 66 in
    Arabic, where the reader's own Arabic covered 6), and a film carries every sourced Arabic name enrich.py
    kept (`aka_ar`: Wikidata's label and aliases, the chain's Arabic) as extra keys;
  - new entry types: `y` a city, `h` a format or premium hall (to its /q/ answer when that page is indexed
    today, else /halls/), `n` a chain (its Arabic and English names; the client neither scores nor lists it
    until W2-P8's chips read it);
  - `s`: the consonant skeleton of a Latin name (skeleton()), so «أفنجرز», «سبايدر» and «اوديسا» find
    Avengers, Spider-Man and The Odyssey however the Arabic is spelled; the client folds an Arabic query
    with skeleton_ar()'s rule (src/js/search.js skel()), and uses it only when no place or person matched
    directly (films are drawn first), so «ستار» lists Star's cinemas, not a film whose name sounds like it.

The header carries the search button and the phone tab bar a «بحث» link (both `[data-search]`, UI redesign
Task 2), and the chunk loads on every page through `page_js["*"]` — the two gaps task-A5-report.md flagged
(no header-button hook, a per-kind list going stale) are closed.

W2-P8 (MASTER-PLAN §2.7): search is a browse surface, not just a lookup box. Before typing, the panel shows
recent searches (local, clearable) and, reusing the same `h`/`n` index entries and the same row markup as a
real search, the formats and chains — never fetching a city's own schedule slice for that empty state. A
time word («الحين»، «الليلة»، «بعد العشا»، «بكرة») navigates the schedule at once with `cinema.when` already
set and `?t=<word>` on the URL, so no extra tap is needed. All of this stays client-side in src/js/search.js;
this module (the index and its build-time normalize/skeleton rules) is unchanged by it."""
import os
import re
import unicodedata

import yaml

from pages.people import People
from site_kit import CITIES, ROOT, UI, Plugin

CSS = ("search",)
LAZY_JS = ("search",)
MALLS_PATH = os.path.join(ROOT, "malls.yaml")

_DIACRITICS = re.compile("[ؐ-ًؚ-ٰٟۖ-ۜ۟-۪ۨ-ۭ"
                          "࣓-࣡ـ]")
_ALEF = re.compile("[إأآٱ]")           # إ أ آ ٱ
_KEEP = re.compile("[^a-z0-9ء-ي]")
_EAST = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")

# formats every chain means the same by (pages/questions.py FORMATS): the /q/where-<slug>/ answer
FORMATS = (("IMAX", "imax"), ("4DX", "4dx"), ("MX4D", "mx4d"), ("SCREENX", "screenx"), ("DOLBY", "dolby"))
# what people type for a city besides its name
CITY_ALIASES = {"ras-al-khaimah": ("RAK",), "umm-al-quwain": ("UAQ",)}


def normalize(s):
    """Fold a name or a typed query to one comparable key: casefold, drop Arabic diacritics/tatweel, unify
    alef (ا/أ/إ/آ/ٱ -> ا), ة -> ه, ى -> ي, ؤ -> و, ئ -> ي, drop ء, ڤ/پ/گ/چ -> ف/ب/ك/ج, then strip every space and punctuation
    mark. The exact same rule runs in src/js/search.js so a typed query matches a name however either one
    was spelled or diacritised."""
    if not s:
        return ""
    s = unicodedata.normalize("NFKC", str(s)).casefold()
    s = _DIACRITICS.sub("", s)
    s = _ALEF.sub("ا", s)
    s = s.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي").replace("ء", "")
    # W1-D2: the Persian letters people type for v, p, g and ch fold onto the Arabic ones («ڤوكس» is فوكس, not «وكس»)
    s = s.replace("ڤ", "ف").replace("پ", "ب").replace("گ", "ك").replace("چ", "ج")
    return _KEEP.sub("", s)


# ------------------------------------------------------------------ the consonant skeleton
# One alphabet of sound classes both scripts fold into, so an Arabic spelling of a Latin name meets it:
# vowels drop (a word's first letter, when a vowel, leaves "a"), h drops, k/g/j/q are one class (ك ق ج غ خ:
# people write a hard g as ق or ج or غ), b/p, f/v, s/z, t/th are one each, sh/ch is "x", and a repeated class
# counts once. Coarse on purpose: it only has to find ~70 films and the people on their pages.
# An Arabic word is folded by normalize() first (so ڤ پ گ چ are ف ب ك ج by then), and each letter U+0621..U+064A
# read as its class here ("." drops it; a, w and y count only as a word's first letter): ب b, ت ث ذ ط t,
# د ض ظ d, ج خ غ ق ك k, ر r, ز س ص s, ش x, ف f, ل l, م m, ن n, ا ع a, و w, ي y. «تش» is read as ش.
_SKT = "......ab.ttk.kdtrssxsdtdak......fkklmn.w.y"
_SK_LAT2 = {"sh": "x", "ch": "x", "th": "t", "ph": "f", "kh": "k", "dh": "d", "bh": "b", "jh": "k", "ck": "k", "qu": "k"}
_SK_LAT1 = {"b": "b", "p": "b", "f": "f", "v": "f", "t": "t", "d": "d", "s": "s", "z": "s", "k": "k", "q": "k",
            "g": "k", "j": "k", "l": "l", "m": "m", "n": "n", "r": "r", "x": "ks"}
_VOWELS = "aeiou"
SKELETON_MIN = 3   # a shorter folded query is too loose to match by skeleton (the client's rule too)


def _squeeze(parts):
    out = ""
    for p in parts:
        for ch in p:
            if ch and (not out or out[-1] != ch):
                out += ch
    return out


def _skel_latin_word(w):
    if w.isdigit():
        return w
    for pre, rep in (("kn", "n"), ("wr", "r"), ("wh", "w"), ("ps", "s"), ("gn", "n")):
        if w.startswith(pre) and len(w) > 2:
            w = rep + w[2:] if rep != "w" else "w" + w[2:]
            break
    parts, i = [], 0
    while i < len(w):
        two, ch = w[i:i + 2], w[i]
        if w.startswith("sch", i) or w.startswith("tch", i):
            parts.append("x"); i += 3; continue
        if two == "gh":
            parts.append("" if w[i + 2:i + 3] in ("", "t") else "k"); i += 2; continue
        if two in _SK_LAT2:
            parts.append(_SK_LAT2[two]); i += 2; continue
        nxt = w[i + 1:i + 2]
        if ch in _VOWELS:
            parts.append("a" if i == 0 else "")
        elif ch == "c":
            parts.append("s" if nxt and nxt in "eiy" else "k")
        elif ch == "w":
            parts.append("w" if i == 0 else "")
        elif ch == "y":
            parts.append("y" if i == 0 and nxt and nxt in _VOWELS else ("a" if i == 0 else ""))
        else:
            parts.append(_SK_LAT1.get(ch, ""))
        i += 1
    return _squeeze(parts)


def skeleton(name):
    """A Latin name's skeleton, one word per space: "The Odyssey" -> "t ads", "Avengers Endgame: Encore" ->
    "afnkrs andkm ankr". "" for a name with no Latin letters."""
    s = unicodedata.normalize("NFKD", str(name or "")).encode("ascii", "ignore").decode().lower()
    s = s.replace("'", "")
    return " ".join(k for k in (_skel_latin_word(w) for w in re.findall(r"[a-z]+|[0-9]+", s)) if k)


def skeleton_ar(query):
    """An Arabic query folded the same way, words joined (the client's skel(), src/js/search.js)."""
    s = str(query or "").translate(_EAST).replace("تش", "ش")
    out = ""
    for w in s.split():
        k = ""
        for i, ch in enumerate(normalize(w)):
            if not ch.isdigit():
                o = ord(ch) - 0x621
                ch = _SKT[o] if 0 <= o < len(_SKT) else "."
                if ch == "." or (i and ch in "awy"):
                    continue
                if k.endswith(ch):
                    continue
            k += ch
        out += k
    return out


def skeleton_match(q, s):
    """The client's skeleton score: 50 when q starts the name's skeleton, 45 when it starts at a later word,
    -1 otherwise (and always -1 below SKELETON_MIN)."""
    if len(q) < SKELETON_MIN or not s:
        return -1
    words = s.split(" ")
    for i in range(len(words)):
        if "".join(words[i:]).startswith(q):
            return 50 if i == 0 else 45
    return -1


# ------------------------------------------------------------------ the index
def _mall_names(cinemas):
    """{cinema id: [the names of the mall it is in]}, from malls.yaml's `cinemas:` lists (only cinemas that exist)."""
    try:
        raw = (yaml.safe_load(open(MALLS_PATH, encoding="utf-8")) or {}).get("malls") or {}
    except OSError:
        return {}
    out = {}
    for m in raw.values():
        for cid in m.get("cinemas") or []:
            if cid in cinemas:
                out.setdefault(cid, []).extend(x for x in (m.get("ar"), m.get("en")) if x)
    return out


def _entry(t, ar, en, path, img=None, more=(), skel=None):
    ar, en = ar or None, en or None
    if not (ar or en) or not path:
        return None
    keys = sorted({k for k in (normalize(x) for x in (ar, en, *more)) if k})
    if not keys:
        return None
    e = {"t": t, "a": ar, "e": en, "p": path, "k": keys}
    if img:
        e["i"] = img
    if skel:
        e["s"] = skel
    return e


def _formats(site):
    """`h` entries: the five formats every chain means the same by, then each chain's own premium halls
    (halls.yaml), each to its /q/ answer when that page is indexed today, else to /halls/; and /halls/ itself."""
    urls = {tuple(u) for u in getattr(site, "urls", ())}
    chains = site.h.y if getattr(site, "h", None) else {}
    names = {}
    for ch, c in chains.items():
        for e in c.get("halls") or []:
            names.setdefault(e["key"], set()).update(x for x in (e.get("name"), e.get("name_ar")) if x)
    out = []
    for key, slug in FORMATS:
        if key not in names:
            continue
        label = next((n for n in sorted(names[key], key=len) if n.isascii()), key)
        path = f"q/where-{slug}" if ("q", f"where-{slug}") in urls else "halls"
        out.append(_entry("h", label, label, path, more=sorted(names[key])))
    fmt = {k for k, _ in FORMATS}
    for ch, c in chains.items():
        ar_ch, en_ch = c.get("name_ar"), c.get("name")
        for e in c.get("halls") or []:
            if e["key"] in fmt:
                continue
            nm = e.get("name") or e["key"]
            slug = re.sub(r"[^a-z0-9]+", "-", e["key"].lower()).strip("-")
            path = f"q/{ch}-{slug}-ticket-price" if ("q", f"{ch}-{slug}-ticket-price") in urls else "halls"
            out.append(_entry("h", f"{nm} في {ar_ch}" if ar_ch else nm, f"{nm} at {en_ch}" if en_ch else nm, path,
                              more=[x for x in (e.get("name_ar"), f"{en_ch or ''} {nm}", f"{ar_ch or ''} {e.get('name_ar') or ''}") if x]))
    out.append(_entry("h", UI["s_halls"][0], UI["s_halls"][1], "halls", more=("القاعات المميزة", "premium halls")))
    return [e for e in out if e]


def build_index(site):
    """Every film, showing or archived: an archived film keeps a real, useful page (pages/people.py links
    to it from "shown before"), and search is a lookup surface, not a listing -- unlike the daily schedule
    slices, hiding it here would just make it unfindable. Ruling (task-A5-review.md, round 2): keep it,
    marked `x` (archived) so the client both ranks it after every showing match and labels it, never
    silently indistinguishable from a film still on."""
    out = []
    for fid, f in site.films.items():
        e = _entry("f", f.get("title_ar"), f.get("title"), f"film/{fid}", f.get("poster"),
                   more=f.get("aka_ar") or (), skel=skeleton(f.get("title")))
        if not e:
            continue
        if f.get("status") == "archived":
            e["x"] = 1
        out.append(e)
    malls = _mall_names(site.cinemas)
    for cid, c in site.cinemas.items():
        path = f"{c.get('city')}/{cid}" if c.get("city") else None
        e = _entry("c", site.cname(cid, "ar"), site.cname(cid, "en"), path,
                   more=(c.get("name_ar"), c.get("name"), *malls.get(cid, ())))
        if e:
            out.append(e)
    for slug, ar, en in CITIES:
        e = _entry("y", ar, en, slug, more=CITY_ALIASES.get(slug, ()))
        if e:
            out.append(e)
    out += _formats(site)
    chains = site.h.y if getattr(site, "h", None) else {}
    for ch in sorted({c["chain"] for c in site.cinemas.values() if c.get("chain")}):
        y = chains.get(ch) or {}
        e = _entry("n", site.h.chain_name(ch, "ar"), site.h.chain_name(ch, "en"), "cinemas", more=(y.get("name"), ch))
        if e:
            out.append(e)
    ppl = People(site)
    for q, p in ppl.p.items():
        ph = ppl.photo(q)
        e = _entry("p", p.get("name_ar"), p.get("name_en"), f"people/{p['slug']}", ph["src"] if ph else None,
                   skel=None if p.get("name_ar") else skeleton(p.get("name_en")))
        if e:
            out.append(e)
    return out


def register(site):
    return Plugin(data={"data/search.json": lambda: build_index(site)},
                  page_js={"*": ("search",)})
