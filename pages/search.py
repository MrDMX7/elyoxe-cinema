"""Bilingual fuzzy search (phase 3, batch A, task A5): a compact index at /data/search.json and the client
chunk src/js/search.js that reads it. No page of its own — this module only feeds data and a lazy chunk.

The index: every film (site.films — showing and archived, each still has a page), every cinema, every mall
(malls.yaml, linked to one of its own cinemas — venue.py's rule: a mall not listed under a cinema's `mall`
entry there is never guessed at), and every person with a real /people/<slug>/ page (pages/people.py's own
`People` filter, imported rather than re-derived, so search never lists someone whose page does not exist).

Per entry: its Arabic/English names, the site path (joined without a leading/trailing slash — the client
builds the language-correct href from `C.base`), a poster/photo where one exists, and `k`: normalised keys
generated BY RULE from the Arabic and English names (see `normalize()`), not hand-written per title. Folding
"Spider-Man", "Spider Man" and "spiderman" all removes spaces/punctuation and case, so they collapse to the
same key on both sides — the query is folded with the exact same rule client-side (src/js/search.js). That
single mechanism is what the brief calls "a few common variants" without anyone listing them by hand.

No new PLUGINS.md hook exists for a header search button (docs/PLUGINS.md's NavItem only renders `<a>` link
text, never a button that opens a panel), so the chunk injects its own button into the header's existing
`.top-in` container — see task-A5-report.md for that gap. Because PLUGINS.md's `page_js` maps a chunk to
page KINDS, not "every page", this module lists every kind this build currently knows so the search chunk
loads everywhere; a page kind added later by another module needs adding here too (also in the report)."""
import os
import re
import unicodedata

import yaml

from pages.people import People
from site_kit import Plugin, ROOT

CSS = ("search",)
LAZY_JS = ("search",)
MALLS_PATH = os.path.join(ROOT, "malls.yaml")

# every page kind known at the time this module was written (build.py / pages/*.py); the missing "every
# page, whatever its kind" hook is exactly this list going stale — task-A5-report.md.
ALL_KINDS = ("home", "city", "cinema", "film", "cards", "card", "halls", "404", "coming", "events", "arabic",
             "prices", "boxoffice", "person", "people", "price", "hall", "tonight", "where", "q", "eid",
             "kids", "summer")

_DIACRITICS = re.compile("[ؐ-ًؚ-ٰٟۖ-ۜ۟-۪ۨ-ۭ"
                          "࣓-࣡ـ]")
_ALEF = re.compile("[إأآٱ]")           # إ أ آ ٱ
_KEEP = re.compile("[^a-z0-9ء-ي]")


def normalize(s):
    """Fold a name or a typed query to one comparable key: casefold, drop Arabic diacritics/tatweel, unify
    alef (ا/أ/إ/آ/ٱ -> ا), ة -> ه, ى -> ي, ؤ -> و, ئ -> ي, drop ء, then strip every space and punctuation
    mark. The exact same rule runs in src/js/search.js so a typed query matches a name however either one
    was spelled or diacritised."""
    if not s:
        return ""
    s = unicodedata.normalize("NFKC", str(s)).casefold()
    s = _DIACRITICS.sub("", s)
    s = _ALEF.sub("ا", s)
    s = s.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي").replace("ء", "")
    return _KEEP.sub("", s)


def _malls(cinemas):
    try:
        raw = (yaml.safe_load(open(MALLS_PATH, encoding="utf-8")) or {}).get("malls") or {}
    except OSError:
        return {}
    out = {}
    for mid, m in raw.items():
        cid = next((c for c in (m.get("cinemas") or []) if c in cinemas), None)
        if not cid or not cinemas[cid].get("city"):
            continue
        out[mid] = {"ar": m.get("ar"), "en": m.get("en"), "path": f"{cinemas[cid]['city']}/{cid}"}
    return out


def _entry(t, ar, en, path, img=None):
    ar, en = ar or None, en or None
    if not (ar or en) or not path:
        return None
    keys = sorted({k for k in (normalize(ar), normalize(en)) if k})
    if not keys:
        return None
    e = {"t": t, "a": ar, "e": en, "p": path, "k": keys}
    if img:
        e["i"] = img
    return e


def build_index(site):
    out = []
    for fid, f in site.films.items():
        e = _entry("f", f.get("title_ar"), f.get("title"), f"film/{fid}", f.get("poster"))
        if e:
            out.append(e)
    for cid, c in site.cinemas.items():
        e = _entry("c", c.get("name_ar"), c.get("name"), f"{c.get('city')}/{cid}" if c.get("city") else None)
        if e:
            out.append(e)
    for mid, m in _malls(site.cinemas).items():
        e = _entry("m", m["ar"], m["en"], m["path"])
        if e:
            out.append(e)
    ppl = People(site)
    for q, p in ppl.p.items():
        ph = ppl.photo(q)
        e = _entry("p", p.get("name_ar"), p.get("name_en"), f"people/{p['slug']}", ph["src"] if ph else None)
        if e:
            out.append(e)
    return out


def register(site):
    return Plugin(data={"data/search.json": lambda: build_index(site)},
                  page_js={k: ("search",) for k in ALL_KINDS})
